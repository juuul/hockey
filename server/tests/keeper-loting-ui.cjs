// Echte app, uitsluitend fictieve lokale gegevens. Geen API of echte accounts/mails.
const assert = require('node:assert/strict')
const puppeteer = require('/usr/src/app/node_modules/puppeteer')
const url = process.env.TEST_URL || 'http://127.0.0.1:5189/'
;(async () => {
 const browser = await puppeteer.launch({executablePath:'/usr/bin/chromium-browser',args:['--no-sandbox']})
 try {
  for(const opstelling of ['2-3-3','zaal-2-1-2']){
   const page = await browser.newPage();await page.setViewport({width:390,height:844})
   const fouten=[];page.on('pageerror',e=>fouten.push(e.message))
   await page.setRequestInterception(true)
   page.on('request',req=>{const u=new URL(req.url());return u.hostname===new URL(url).hostname&&!u.pathname.includes('/api/')?req.continue():req.abort()})
   await page.evaluateOnNewDocument(({opstelling,afgesloten})=>{
    localStorage.clear();localStorage.setItem('hockey_test_backend','apart-v1')
    localStorage.setItem('hockey_test_opstelling',JSON.stringify(opstelling))
    localStorage.setItem('hockey_test_spelers',JSON.stringify(Array.from({length:12},(_,i)=>({id:'kind'+i,naam:'T Kind '+i,positie:i===0?'K':'LW',inVeld:i===0,isKeeper:i===0,meedoen:i!==2,wisselCount:2}))))
    localStorage.setItem('hockey_test_vaste_posities',JSON.stringify(afgesloten?{kind1:['K','']}:{}))
    if(afgesloten)localStorage.setItem('hockey_test_wedstrijd',JSON.stringify({datum:null,clubId:null,thuis:true,afgesloten:'fictief'}))
   },{opstelling,afgesloten:false})
   await page.goto(url);await page.waitForSelector('.player-slot.keeper')
   assert.match(await page.$eval('.player-slot.keeper',e=>e.textContent),/T Kind 0/)
   await page.click('.tab-btn[aria-label="Voorkeur"]')
   await page.select('[aria-label="1e keuze voor T Kind 1"]','K')
   await page.select('[aria-label="1e keuze voor T Kind 2"]','K')
   await page.click('.tab-btn[aria-label="Wedstrijd"]')
   const voor=await page.evaluate(()=>JSON.parse(localStorage.getItem('hockey_test_spelers')))
   const klik=async text=>page.evaluate(text=>{const b=[...document.querySelectorAll('button')].find(b=>b.textContent.trim()===text);if(!b)throw Error('Knop ontbreekt: '+text);b.click()},text)
   await klik('Nieuwe opstelling');await page.waitForSelector('.reset-modal-overlay')
   await klik('Ja, nieuwe opstelling')
   await page.waitForFunction(()=>JSON.parse(localStorage.getItem('hockey_test_spelers')).find(s=>s.isKeeper)?.id==='kind1')
   assert.match(await page.$eval('.player-slot.keeper',e=>e.textContent),/T Kind 1/)
   const ps=await page.evaluate(()=>JSON.parse(localStorage.getItem('hockey_test_spelers')))
   assert.equal(ps.filter(s=>s.isKeeper).length,1)
   assert.equal(ps.filter(s=>s.inVeld).length,opstelling.startsWith('zaal')?6:9)
   assert.equal(ps.find(s=>s.id==='kind2').inVeld,false)
   assert.ok(ps.every(s=>s.wisselCount===2))
   await page.click('[aria-label="Undo"]')
   await page.waitForFunction(voor=>JSON.stringify(JSON.parse(localStorage.getItem('hockey_test_spelers')))===JSON.stringify(voor),{},voor)
   assert.match(await page.$eval('.player-slot.keeper',e=>e.textContent),/T Kind 0/)
   assert.deepEqual(fouten,[])
   await page.close()
  }
  // Een nieuwe wedstrijd gebruikt dezelfde keeperloting en reset wel de tellers.
  const p=await browser.newPage();await p.setRequestInterception(true)
  p.on('request',req=>{const u=new URL(req.url());return u.hostname===new URL(url).hostname&&!u.pathname.includes('/api/')?req.continue():req.abort()})
  await p.evaluateOnNewDocument(()=>{
   localStorage.clear();localStorage.setItem('hockey_test_backend','apart-v1')
   localStorage.setItem('hockey_test_opstelling',JSON.stringify('zaal-2-1-2'))
   localStorage.setItem('hockey_test_spelers',JSON.stringify(Array.from({length:8},(_,i)=>({id:'kind'+i,naam:'T Kind '+i,positie:i===0?'K':'LW',inVeld:i===0,isKeeper:i===0,meedoen:true,wisselCount:3}))))
   localStorage.setItem('hockey_test_vaste_posities',JSON.stringify({kind1:['K','']}))
   localStorage.setItem('hockey_test_wedstrijd',JSON.stringify({datum:null,clubId:null,thuis:true,afgesloten:'fictief'}))
  })
  await p.goto(url);await p.waitForFunction(()=>[...document.querySelectorAll('button')].some(b=>b.textContent==='Nieuwe wedstrijd'))
  await p.evaluate(()=>[...document.querySelectorAll('button')].find(b=>b.textContent==='Nieuwe wedstrijd').click())
  await p.waitForFunction(()=>JSON.parse(localStorage.getItem('hockey_test_spelers')).find(s=>s.isKeeper)?.id==='kind1')
  assert.ok(await p.evaluate(()=>JSON.parse(localStorage.getItem('hockey_test_spelers')).every(s=>s.wisselCount===0)))
  console.log('KEEPER_LOTING_UI_OK: voorkeur via app, keeper op doel in veld/zaal, afwezige overgeslagen, precies één keeper, tellers behouden, Undo herstelt en Nieuwe wedstrijd loot keeper/reset tellers.')
 } finally {await browser.close()}
})().catch(e=>{console.error(e);process.exit(1)})
