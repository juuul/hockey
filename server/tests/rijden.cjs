// Volledige rijbeurtflow in de app met fictieve lokale spelers; geen echte API of mails.
const assert = require('node:assert/strict')
const puppeteer = require('/usr/src/app/node_modules/puppeteer')
const appUrl = process.env.TEST_URL || 'http://127.0.0.1:5187/'
;(async () => {
  const browser = await puppeteer.launch({ executablePath: '/usr/bin/chromium-browser', args: ['--no-sandbox'] })
  try {
    const page = await browser.newPage()
    const fouten = []
    page.on('pageerror', e => fouten.push(e.message))
    await page.setViewport({ width: 360, height: 640 })
    await page.evaluateOnNewDocument(opstelling => {
      localStorage.clear()
      localStorage.setItem('hockey_test_backend', 'apart-v1')
      if (opstelling) localStorage.setItem('hockey_test_opstelling', JSON.stringify(opstelling))
      localStorage.setItem('hockey_test_kinderen_lokaal', '["kind0"]')
      localStorage.setItem('hockey_test_spelers', JSON.stringify(Array.from({ length: 9 }, (_, i) => ({ id: `kind${i}`, naam: `Testkind ${i}`, positie: 'LW', inVeld: true, meedoen: true, wisselCount: 0, isKeeper: i === 0 }))))
      localStorage.setItem('hockey_test_programma', JSON.stringify([{ id: 'fictievewedstrijd', datum: `${new Date().getFullYear() + 1}-01-01`, tot: '', soort: 'wedstrijd', clubId: '', tegenstander: '', thuis: false, verzamelen: '', spelen: '', fruit: '', begeleider1: '', begeleider2: '', notitie: '' }]))
      const planning = JSON.parse(localStorage.getItem('hockey_test_programma'))
      planning.push({ ...planning[0], id: 'voorlopig', datum: `${new Date().getFullYear() + 1}-01-08`, thuis: true, bronPlanning: { id: 'planning', status: 'speeldag', spelvorm: 'Veld' } })
      localStorage.setItem('hockey_test_programma', JSON.stringify(planning))
      sessionStorage.setItem('hockey_test_tabblad', 'programma')
    }, process.env.OPSTELLING || '')
    await page.setRequestInterception(true)
    page.on('request', req => {
      const u = new URL(req.url())
      return u.hostname === new URL(appUrl).hostname && !u.pathname.includes('/api/') ? req.continue() : req.abort()
    })
    await page.goto(appUrl)
    await page.waitForSelector('.prog-knoppenrij button')
    assert.equal(await page.$eval('.prog-waar.uit', e => e.textContent), 'Uit', 'Ook zonder tegenstander zichtbaar')
    if (process.env.OPSTELLING === '2-3-3') {
      assert.equal(await page.$eval('.prog-kaart', e => e.textContent.includes('begeleiding: n.v.t.')), true, 'O11 uit: eigen begeleiding n.v.t.')
    }
    assert.equal(await page.$eval('.prog-waar.onbekend', e => e.textContent), 'Thuis/uit nog onbekend')
    await page.click('.prog-knoppenrij button')
    await page.waitForSelector('.modal.show .prog-velden')
    const autoSelects = () => page.$$eval('.prog-veld', els => els.filter(e => e.textContent.trim().startsWith('🚗 Auto')).map(e => e.querySelector('select').value))
    assert.deepEqual(await autoSelects(), ['', '', ''])
    await page.evaluate(() => {
      const select = [...document.querySelectorAll('.prog-veld')].find(e => e.textContent.trim().startsWith('🚗 Auto 1')).querySelector('select')
      select.value = 'kind0'; select.dispatchEvent(new Event('change', { bubbles: true }))
    })
    assert.deepEqual(await autoSelects(), ['kind0', '', ''])
    assert.equal(await page.$$eval('.prog-veld', els => els.find(e => e.textContent.trim().startsWith('🍎 Fruit')).querySelector('select').value), 'kind0')
    const begeleiders = () => page.$$eval('.prog-veld', els => els.filter(e => /^(🏑 Spelbegeleiding|🏑 Scheidsrechter)/.test(e.textContent.trim())).map(e => e.querySelector('select').value))
    assert.deepEqual(await begeleiders(), ['2-1-2', '2-3-3'].includes(process.env.OPSTELLING) ? ['-', '-'] : process.env.OPSTELLING === '2-3-2' ? ['kind0', '-'] : ['kind0', ''])
    assert.ok(await page.evaluate(() => {
      const velden = [...document.querySelectorAll('.modal.show .prog-veld')]
      const scheids = velden.filter(e => /^(🏑 Spelbegeleiding|🏑 Scheidsrechter)/.test(e.textContent.trim()))
      const auto = velden.find(e => e.textContent.trim().startsWith('🚗 Auto'))
      return scheids.length === 2 && !!(scheids[1].compareDocumentPosition(auto) & Node.DOCUMENT_POSITION_FOLLOWING)
    }))
    assert.ok(!await page.$eval('.modal.show', e => /De eerste ouderkeuze|kinderen ·|geen speelbegeleider ingepland|De thuisclub regelt de speelbegeleider/.test(e.textContent)))
    for (const [i, kind] of [[0, 'kind1'], [1, 'kind2']]) await page.evaluate(({i, kind}) => {
      const select = [...document.querySelectorAll('.modal.show .prog-veld')].filter(e => /^(🏑 Spelbegeleiding|🏑 Scheidsrechter)/.test(e.textContent.trim()))[i].querySelector('select')
      select.value = kind; select.dispatchEvent(new Event('change', { bubbles: true }))
    }, {i, kind})
    assert.deepEqual(await begeleiders(), ['kind1', 'kind2'])
    await page.evaluate(() => [...document.querySelectorAll('[aria-label="Thuis of uit"] button')].find(b => b.textContent === 'Thuis').click())
    assert.deepEqual(await autoSelects(), [])
    await page.evaluate(() => [...document.querySelectorAll('[aria-label="Thuis of uit"] button')].find(b => b.textContent === 'Uit').click())
    assert.deepEqual(await autoSelects(), ['kind0', '', ''])
    assert.deepEqual(await begeleiders(), ['kind1', 'kind2'], 'Thuis/uit bewaart gekozen ouders')
    await page.evaluate(() => [...document.querySelectorAll('.modal-actions button')].find(b => b.textContent === 'Opslaan').click())
    await page.waitForFunction(() => !document.querySelector('.modal.show'))
    assert.deepEqual(await page.evaluate(() => JSON.parse(localStorage.getItem('hockey_test_programma'))[0].rijders), ['kind0', '', ''])
    assert.deepEqual(await page.evaluate(() => { const p = JSON.parse(localStorage.getItem('hockey_test_programma'))[0]; return [p.begeleider1, p.begeleider2] }), ['kind1', 'kind2'])
    assert.equal(await page.$eval('.prog-kaart', e => e.textContent.includes('ouder van Testkind 0 · nog 2 chauffeurs nodig') && e.textContent.includes('Jij: rijden')), true)
    await page.evaluate(() => [...document.querySelectorAll('button')].find(b => b.textContent === 'Alleen mijn beurten').click())
    assert.equal((await page.$$('.prog-kaart')).length, 1)
    await page.evaluate(() => [...document.querySelectorAll('button')].find(b => b.textContent.includes('Datum toevoegen')).click())
    await page.waitForSelector('.modal.show .prog-velden')
    assert.deepEqual(await begeleiders(), ['2-1-2', '2-3-2'].includes(process.env.OPSTELLING) ? ['', '-'] : ['', ''])
    assert.deepEqual(await autoSelects(), [])
    await page.evaluate(() => [...document.querySelectorAll('.modal-actions button')].find(b => b.textContent === 'Annuleren').click())
    await page.waitForFunction(() => !document.querySelector('.modal.show'))
    await page.evaluate(() => [...document.querySelectorAll('button')].find(b => b.textContent === 'Begeleiding').click())
    await page.waitForSelector('[aria-label="Standaard spelbegeleiding"]')
    await page.evaluate(() => {
      const select = [...document.querySelectorAll('.prog-veld')].find(e => e.textContent.trim().startsWith('Eigen begeleiders bij thuis')).querySelector('select')
      select.value = '2'; select.dispatchEvent(new Event('change', { bubbles: true }))
    })
    await page.evaluate(() => [...document.querySelectorAll('.modal-actions button')].find(b => b.textContent === 'Klaar').click())
    await page.waitForFunction(() => !document.querySelector('.modal.show'))
    await page.evaluate(() => [...document.querySelectorAll('button')].find(b => b.textContent.includes('Datum toevoegen')).click())
    await page.waitForSelector('.modal.show .prog-velden')
    assert.deepEqual(await begeleiders(), ['', ''])
    assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('hockey_test_instellingen')).begeleidingThuis), 2)
    assert.deepEqual(fouten, [])
    console.log('RIJDEN_UI_OK: beide fluitkeuzes altijd invulbaar boven auto’s, zonder uitleg, bewaren en thuis/uit behoud; rijbeurten, automatische koppeling en Mijn kind blijven werken.')
  } finally { await browser.close() }
})().catch(e => { console.error(e); process.exit(1) })
